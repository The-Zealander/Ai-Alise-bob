import ollama

def model_llama(msg, mdl):

    msg1 = """. (*&*) This prompt was generated by the llama3.2 model as you requested. You can now either (a) forward this response to the user if you
    think it's good enough, or (b) prompt llama3.2 again. As always, if you want to prompt llama3.2, you should start your message with 'llama3.2' followed
    by a prompt for the llama3.2 model."""
    messages = [
        {'role': 'system', 'content': """You are a helpful assistant and are apart of a
        small agentic program consisting of you and a smaller model lfm3.
        The smaller model, the lfm3 model, is responsible for delegating tasks between the two of you,
        so a prompt will only reach you if lfm3 assesses that the task is too complex for itself."""},
        {'role': 'user', 'content': msg}
    ]

    response = ollama.chat(model=mdl, messages=messages)
    rsp = "\n" + response.message.content + msg1
    
    return rsp
